class LandingEventIn(BaseModel, extra="forbid"):
    t: str = Field(max_length=40)
    meta: dict[str, Any] | None = None

    @field_validator("t")
    @classmethod
    def _known(cls, v: str) -> str:
        if v not in LANDING_EVENT_TYPES:
            raise ValueError("unknown event type")
        return v

    @field_validator("meta")
    @classmethod
    def _small(cls, v: dict[str, Any] | None) -> dict[str, Any] | None:
        """Bounded in both directions: at most five keys, and values that are
        short strings or plain numbers. The metadata is a label — which section,
        which percentage, which button — and anything larger arriving here is
        somebody using a public endpoint as free storage."""
        if v is None:
            return None
        if len(v) > 5:
            raise ValueError("too many metadata keys")
        out: dict[str, Any] = {}
        for key, value in v.items():
            if not isinstance(key, str) or len(key) > 40:
                raise ValueError("bad metadata key")
            if isinstance(value, bool) or value is None:
                continue
            if isinstance(value, int):
                out[key] = value
            elif isinstance(value, str):
                trimmed = value.strip()[:120]
                if trimmed:
                    out[key] = trimmed
            else:
                raise ValueError("bad metadata value")
        return out


