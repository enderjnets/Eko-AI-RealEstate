@router.post("/landing")
async def landing_events(request: Request, db: AsyncSession = Depends(get_db)) -> Response:
    """What a visitor did on the marketing page, before there was a lead.

    Unauthenticated and uncaptcha'd, because it is sent by a page anyone can
    open and by `navigator.sendBeacon`, which cannot solve a challenge and
    cannot wait for one. Three things stand in for the captcha, and the third
    is the one that actually bounds the table: its own rate budget, a 16 KB
    body of at most 25 events with a closed set of names, and a **per-agency
    daily cap on new sessions**. Without that cap the rate limit bounds the
    speed of writing permanent rows and nothing bounds their number.

    Always 204, even when it declines to do anything. The sender has nothing
    useful to do with the distinction, and a public endpoint that answers
    differently for a valid and an invalid form key is an oracle for
    enumerating an operator's tenants. Honest caveat, since a comment that
    overclaims is worse than none: the STATUS is identical, but a resolvable
    key does more work than an unresolvable one, so the two are distinguishable
    by timing to anyone willing to average enough samples.

    The body is read and parsed by hand rather than declared as a Pydantic
    parameter because `sendBeacon` sends `text/plain` — Chromium refuses a JSON
    Blob from a beacon in some contexts — and FastAPI would answer a valid
    batch with 422 purely over the content type.
    """
    ip = client_ip(request)
    if _ev_ip_limited(ip):
        return Response(status_code=429)

    # Charged BEFORE the body is read and parsed. The sibling endpoint carries
    # a comment about the opposite order being a past outage, and the reasoning
    # inverts here: `capture` charges last so a request the captcha will refuse
    # cannot spend the platform's budget. There is no captcha on this path, so
    # a caller rotating the client-IP header would otherwise buffer 16 KB and
    # run a JSON parse per request without ever touching the ceiling.
    if _ev_global_limited():
        _warn_once(_global_warned, "landing", "Landing beacon ceiling reached")
        return Response(status_code=429)

    raw = await request.body()
    if len(raw) > EVENTS_MAX_BODY:
        return Response(status_code=413)
    try:
        payload = json.loads(raw) if raw else None
        body = LandingBatchIn.model_validate(payload)
    except Exception as exc:  # noqa: BLE001
        # 400 for both a malformed body and one that fails validation — the
        # sender is our own script and a distinguishing error helps nobody but
        # somebody probing the schema. But it is LOGGED, once per window: the
        # tracker is the only caller, so a schema drift on its side would make
        # every batch 400 and leave the table at zero with nothing anywhere
        # saying why, and `sendBeacon` has no error handler to notice.
        _warn_once(_reject_warned, "landing", f"Landing beacon rejected: {exc}")
        return Response(status_code=400)

    if not get_settings().LANDING_EVENTS_ENABLED:
        return Response(status_code=204)

    try:
        org_id = await webhook_org_or_refuse(
            CHANNEL_WEB, body.form, fallback_when_unmapped=not body.form
        )
    except WebhookOrgUnresolved as exc:
        log.info("Dropping landing beacon — %s", exc)
        return Response(status_code=204)

    # Bound BEFORE the first query on `db`: the org id is injected into the
    # transaction when it begins, so a query issued before this point runs with
    # an empty `app.current_org_id` and, under default-deny RLS, sees nothing.
    set_org_id(org_id)

    now = datetime.now(UTC)
    batch = [(e.t, e.meta or {}) for e in body.events]

    try:
        session_id = await _landing_session_id(db, org_id, body, request, now)
        if session_id is None:
            return Response(status_code=204)

        await db.execute(
            update(LandingSession)
            .where(LandingSession.id == session_id)
            .values(**merge_values(fold_events(batch), now))
        )
        db.add_all(new_events(org_id, session_id, batch, now))
        await db.commit()
    except Exception:
        await db.rollback()
        log.exception("Landing beacon failed")
        # Still 204: the page must not learn anything from a failure here, and
        # a beacon has nobody to report to.
        return Response(status_code=204)

    return Response(status_code=204)


async def _landing_session_id(
    db: AsyncSession,
    org_id: int,
    body: LandingBatchIn,
    request: Request,
    now: datetime,
) -> int | None:
    """The id of this visit's session row, creating it if this is its first
    beacon. None when the agency has already opened its quota of sessions
    today, which is the only thing bounding how many permanent rows an
    anonymous caller can create.

    The cap is on CREATION, not on beacons: a visit already recorded keeps
    merging, so a real visitor is never truncated mid-page — only a caller
    inventing session keys is stopped.
    """
    found = (
        await db.execute(
            select(LandingSession.id).where(
                LandingSession.org_id == org_id,
                LandingSession.session_key == body.session,
            )
        )
    ).scalar_one_or_none()
    if found is not None:
        return found

    if await _sessions_today(db, org_id, now) >= get_settings().LANDING_SESSIONS_PER_DAY:
        _warn_once(
            _cap_warned,
            org_id,
            f"Landing session cap reached for organization {org_id}; new visits "
            "are not being recorded until tomorrow",
        )
        return None

    attribution = clean_attribution(body.utm)
    host = referrer_host_of(body.referrer)
    ua = request.headers.get("user-agent")
    country, region, city = geo_of(request.headers)

    # Core INSERT, not the ORM: `before_flush` is what stamps `org_id` on this
    # project's tables, and it never sees a Core statement. Hence the explicit
    # value — without it the policy's WITH CHECK refuses the row.
    inserted = (
        await db.execute(
            pg_insert(LandingSession)
            .values(
                org_id=org_id,
                session_key=body.session,
                first_seen_at=now,
                last_seen_at=now,
                landing_path=_path_only(body.path),
                lang=body.lang,
                utm_source=attribution.get("utm_source"),
                utm_medium=attribution.get("utm_medium"),
                utm_campaign=attribution.get("utm_campaign"),
                utm_content=attribution.get("utm_content"),
                utm_term=attribution.get("utm_term"),
                referrer_host=host,
                source=source_of(attribution.get("utm_source"), host),
                device=device_of(ua),
                browser=browser_of(ua),
                os=os_of(ua),
                in_app=in_app_of(ua),
                country=country,
                region=region,
                city=city,
                screen_w=body.screen_w,
            )
            # First touch wins, exactly as it does for a lead's attribution: a
            # visitor who reloads with a different query string has not changed
            # where they came from. Also the race: two first beacons for one
            # visit, and the loser reads the winner's row below.
            .on_conflict_do_nothing(index_elements=["org_id", "session_key"])
            .returning(LandingSession.id)
        )
    ).scalar_one_or_none()
    if inserted is not None:
        return inserted

    return (
        await db.execute(
            select(LandingSession.id).where(
                LandingSession.org_id == org_id,
                LandingSession.session_key == body.session,
            )
        )
    ).scalar_one_or_none()


async def _sessions_today(db: AsyncSession, org_id: int, now: datetime) -> int:
    """How many visits this agency has opened since local midnight.

    Local, not UTC, because every number this feature produces is read against
    the agency's own day and a cap that resets at 5pm Denver time would be
    surprising in exactly the way an operator does not need. Counted through a
    LIMIT so the scan stops at the cap instead of walking a busy day's rows.
    """
    cap = get_settings().LANDING_SESSIONS_PER_DAY
    zone = await _agency_zone(db)
    midnight = now.astimezone(zone).replace(hour=0, minute=0, second=0, microsecond=0)
    window = (
        select(LandingSession.id)
        .where(
            LandingSession.org_id == org_id,
            LandingSession.first_seen_at >= midnight.astimezone(UTC),
        )
        .limit(cap)
        .subquery()
    )
    return (
        await db.execute(select(func.count()).select_from(window))
    ).scalar_one()


async def _agency_zone(db: AsyncSession):
    """The acting agency's timezone, or UTC if it has not set a usable one."""
    from app.models import AgentSettings
    from app.services.timezones import resolve_zone

    name = (
        await db.execute(select(AgentSettings.timezone).limit(1))
    ).scalar_one_or_none()
    return resolve_zone(name or "") or UTC


@router.api_route("/content/{piece_id}/media", methods=["GET", "HEAD"])
async def public_media(request: Request, piece_id: int):
    """The video, for the platform that is about to post it.

    Unauthenticated because Buffer has no session and cannot get one: it takes
    a URL and downloads from it when the post goes out. The gate is the piece's
    status, not the address — see `services/media_public.py` for why the signed
    link this repo would otherwise reach for cannot work here.

    Range requests are answered here rather than left to `FileResponse`, which
    in this Starlette version ignores them and returns the whole file with a
    200. Media fetchers ask for ranges, and a client that insists would see a
    broken video hours after the post was created.

    **HEAD as well as GET, and that is not tidiness.** Starlette's own `Route`
    adds HEAD to anything that answers GET; FastAPI's `APIRoute` does not, so
    `@router.get` alone returns 405 to a HEAD. Buffer asks HEAD first to see
    whether the media is really there, and on the 405 gave up with "Video could
    not be read from its URL" — a message that points at the file, the URL and
    the tunnel, none of which were the problem. Measured on the first real
    publish attempt: `HEAD /api/v1/public/content/3/media 405`.
    """
    path = await resolve_public_media(piece_id)
    if path is None:
        # The same answer for "no such piece", "not approved" and "file gone".
        raise HTTPException(status_code=404, detail="Not found")

    size = path.stat().st_size
    # Nothing in between may keep a copy: an edit revokes the piece's approval,
    # and a cached body would outlive that decision.
    headers = {"Cache-Control": "no-store", "Accept-Ranges": "bytes"}

    if request.method == "HEAD":
        # The headers a fetcher is asking for, and no body — the point of the
        # request is to learn the size and type before spending the download.
        return Response(
            status_code=200,
            media_type="video/mp4",
            headers={**headers, "Content-Length": str(size)},
        )

    try:
        span = parse_range(request.headers.get("range"), size)
    except ValueError:
        # Saying so, rather than sending bytes nobody asked for and letting the
        # client believe it got what it wanted.
        return Response(
            status_code=416, headers={**headers, "Content-Range": f"bytes */{size}"}
        )

    if span is None:
        return FileResponse(path, media_type="video/mp4", headers=headers)

    first, last = span
    return StreamingResponse(
        read_range(path, first, last),
        status_code=206,
        media_type="video/mp4",
        headers={
            **headers,
            "Content-Range": f"bytes {first}-{last}/{size}",
            "Content-Length": str(last - first + 1),
        },
    )
