# What a landing session key looks like: 32 hex characters, generated by the
# page. Enforced by the beacon's schema (a malformed one there is a client bug
# and there is nothing to lose by refusing it) and merely *checked* on the
# capture path, where refusing would cost a lead.
_SESSION_KEY = re.compile(r"[0-9a-f]{32}")

# ── Rate limiting ────────────────────────────────────────────────────────
# Two windows, and the second is the one that matters. A per-IP limit alone is
# decorative behind a proxy: the client IP is read from a header, and anyone
# willing to rotate that header has an unlimited per-IP budget. The global
# ceiling is what bounds the damage regardless of how many identities the
# caller invents.
#
# In-process counters are correct here only because the app is pinned to a
# single uvicorn worker — the same constraint main.py documents for the three
# background loops. Under `--workers N` these become N independent budgets and
# belong in Redis alongside those loops.
PER_IP_LIMIT = 5
PER_IP_WINDOW = 600.0
GLOBAL_LIMIT = 60
GLOBAL_WINDOW = 600.0
# Bounded so a flood of distinct (or forged) addresses cannot grow the map
# without limit — the memory itself would otherwise be the attack.
MAX_TRACKED_IPS = 5_000

_hits: dict[str, deque[float]] = {}
_global_hits: deque[float] = deque()

# The landing beacons get their OWN budget, and that is the whole point of
# these four constants existing beside the four above rather than reusing them.
# One ordinary visit sends a page view, a section view, a scroll depth and
# maybe a tap — four attempts against a per-address budget of five. Sharing the
# counters would mean a visitor who reads the page attentively can no longer
# submit the form, which is precisely backwards.
#
# The numbers are high because the work is small (one upsert and a few inserts,
# no captcha call, no outbound mail) and low enough that a script cannot fill
# the table from one address unattended.
EVENTS_PER_IP_LIMIT = 60
EVENTS_PER_IP_WINDOW = 600.0
EVENTS_GLOBAL_LIMIT = 3_000
EVENTS_GLOBAL_WINDOW = 600.0
# 16 KB: a full batch of 25 events, each with its metadata, plus the attribution
# and the referrer, fits with room to spare — and it is sixteen times tighter
# than the 256 KB every other route gets by default.
EVENTS_MAX_BODY = 16_384
EVENTS_MAX_PER_BATCH = 25

_ev_hits: dict[str, deque[float]] = {}
_ev_global_hits: deque[float] = deque()

# And the partner brief gets a THIRD budget, for the same reason the beacons
# got a second one: the people who open it are the two agents this install
# exists for, and a budget shared with lead capture would mean Natalia
# re-reading the page on a bad signal is what stops a seller's form from being
# written. Backwards in exactly the way the comment above describes.
#
# Generous per address because the page autosaves as they type — a careful pass
# through nine names is easily forty saves — and bounded globally because the
# token is the only credential: somebody who has a link must not be able to
# spend the install's capacity with it.
BRIEF_PER_IP_LIMIT = 120
BRIEF_PER_IP_WINDOW = 600.0
BRIEF_GLOBAL_LIMIT = 1_200
BRIEF_GLOBAL_WINDOW = 600.0
# 64 KB. The answers are nine short verdicts and a handful of free-text notes;
# this is two orders of magnitude more than that and still small enough that
# the column can never become somebody's file store.
BRIEF_MAX_ANSWERS = 65_536

_brief_hits: dict[str, deque[float]] = {}
_brief_global_hits: deque[float] = deque()

# A beacon endpoint that logs per request is an amplifier: the cheapest way to
# fill an operator's disk would be to send it rubbish. These remember the last
# day each condition was reported, so a flood produces one line, not a million.
_global_warned: dict[object, date] = {}
_reject_warned: dict[object, date] = {}
_cap_warned: dict[object, date] = {}


def _warn_once(seen: dict[object, date], key: object, message: str) -> None:
    today = datetime.now(UTC).date()
    if seen.get(key) == today:
        return
    seen[key] = today
    log.warning("%s", message)


def _path_only(path: str | None) -> str | None:
    """The path with any query string removed.

    The tracker sends `location.pathname`, but a client is a client: if one
    ever sends `pathname + search`, a URL carrying an email address in a
    parameter would land verbatim in a column, against the promise that nothing
    identifying is stored. Cut here, where it cannot be forgotten.
    """
    cleaned = clip(path)
    if cleaned is None:
        return None
    return cleaned.split("?", 1)[0].split("#", 1)[0] or "/"


def _prune(window: deque[float], now: float, span: float) -> None:
    while window and now - window[0] > span:
        window.popleft()


def _charge_ip(
    store: dict[str, deque[float]], ip: str, limit: int, span: float, now: float | None
) -> bool:
    """Charge one address against a bounded per-address budget."""
    stamp = time.monotonic() if now is None else now
    window = store.get(ip)
    if window is None:
        if len(store) >= MAX_TRACKED_IPS:
            # Drop the coldest tracked address rather than refuse service.
            coldest = min(store, key=lambda k: store[k][-1] if store[k] else 0.0)
            store.pop(coldest, None)
        window = store[ip] = deque()
    _prune(window, stamp, span)
    if len(window) >= limit:
        return True
    window.append(stamp)
    return False


def _ip_limited(ip: str, now: float | None = None) -> bool:
    """Charge this address for a capture attempt; say whether it is over budget.

    Charged for EVERY attempt that reaches it, including honeypot hits and
    submissions the captcha will reject. The budget is per address and bounded,
    so spending it on refused work costs the caller and nobody else.
    """
    return _charge_ip(_hits, ip, PER_IP_LIMIT, PER_IP_WINDOW, now)


def _ev_ip_limited(ip: str, now: float | None = None) -> bool:
    """The same, against the beacons' own budget. See EVENTS_PER_IP_LIMIT."""
    return _charge_ip(_ev_hits, ip, EVENTS_PER_IP_LIMIT, EVENTS_PER_IP_WINDOW, now)


def _global_limited(now: float | None = None) -> bool:
    """Charge the platform-wide budget, and say whether it is exhausted.

    Deliberately charged LAST — after the honeypot, after the per-IP budget and
    after the captcha. It used to be charged first, which made it a kill switch
    anyone could hold down: sixty tokenless posts from sixty forged addresses
    were each refused with 400 and each still consumed a slot, so the captcha
    that is supposed to be the defence a script cannot outspend was bypassed
    for availability, and every agency on the install lost lead capture for ten
    minutes. Now a request only spends this budget once it has proven it is
    worth writing.
    """
    stamp = time.monotonic() if now is None else now
    _prune(_global_hits, stamp, GLOBAL_WINDOW)
    if len(_global_hits) >= GLOBAL_LIMIT:
        return True
    _global_hits.append(stamp)
    return False


def _brief_ip_limited(ip: str, now: float | None = None) -> bool:
    """Charge this address against the brief budget. See BRIEF_PER_IP_LIMIT."""
    return _charge_ip(_brief_hits, ip, BRIEF_PER_IP_LIMIT, BRIEF_PER_IP_WINDOW, now)


def _brief_global_limited(now: float | None = None) -> bool:
    """Charge the platform-wide brief budget. Its own, never capture's."""
    stamp = time.monotonic() if now is None else now
    _prune(_brief_global_hits, stamp, BRIEF_GLOBAL_WINDOW)
    if len(_brief_global_hits) >= BRIEF_GLOBAL_LIMIT:
        return True
    _brief_global_hits.append(stamp)
    return False


def _ev_global_limited(now: float | None = None) -> bool:
    """Charge the platform-wide beacon budget. Separate from capture's, so a
    flood of beacons can never be what stops a lead from being written."""
    stamp = time.monotonic() if now is None else now
    _prune(_ev_global_hits, stamp, EVENTS_GLOBAL_WINDOW)
    if len(_ev_global_hits) >= EVENTS_GLOBAL_LIMIT:
        return True
    _ev_global_hits.append(stamp)
    return False


def reset_rate_limits() -> None:
    """Test seam. Nothing in the app calls this."""
    _hits.clear()
    _global_hits.clear()
    _ev_hits.clear()
    _ev_global_hits.clear()
    _brief_hits.clear()
    _brief_global_hits.clear()


def client_ip(request: Request) -> str:
    """The visitor's address, as well as it can be known.

    `CF-Connecting-IP` first: Cloudflare overwrites it on every request, so a
    client cannot forge it through the tunnel this install actually runs behind.
    `X-Forwarded-For` is next and is only as trustworthy as whatever set it —
    hence the global ceiling above, which does not depend on any of this being
    honest.
    """
    return _client_ip_parts(request)[0]


def _client_ip_parts(request: Request) -> tuple[str, bool]:
    """(address, came_from_a_proxy_header).

    The flag matters for Turnstile. When neither header is present the socket
    peer is NOT the visitor: the POST is proxied by the Next.js server through
    its `/api/*` rewrite, so `request.client.host` is the frontend container's
    address on the Docker bridge. Sending that to Cloudflare as `remoteip` is a
    classic source of spurious verification failures — the field is optional,
    and omitting it is better than asserting something false.
    """
    cf = (request.headers.get("cf-connecting-ip") or "").strip()
    if cf:
        return cf[:45], True
    forwarded = (request.headers.get("x-forwarded-for") or "").split(",")[0].strip()
    if forwarded:
        return forwarded[:45], True
    return (request.client.host if request.client else "unknown")[:45], False


async def _turnstile_ok(token: str | None, ip: str | None) -> bool:
    """Verify a Turnstile token, or pass when no secret is configured.

    Configured-but-unreachable fails CLOSED. A captcha that waves everyone
    through whenever Cloudflare has a bad minute is not a captcha, and this is
    the only defence here that a determined script cannot simply outspend.
    """
    secret = (get_settings().TURNSTILE_SECRET or "").strip()
    if not secret:
        return True
    if not token:
        return False
    payload = {"secret": secret, "response": token}
    if ip:
        payload["remoteip"] = ip
    try:
        async with httpx.AsyncClient(timeout=10.0) as client:
            response = await client.post(TURNSTILE_VERIFY_URL, data=payload)
            return bool(response.json().get("success"))
    except Exception as exc:  # noqa: BLE001
        log.error("Turnstile verification failed to complete: %s", exc)
        return False


class CalculatorIn(BaseModel):
    """What the visitor typed on /calculator, and the sliders they moved.

    Inputs and overrides only — never the result. The server recomputes it
    (`services/calculator.build_snapshot`) before anything is stored, so a
    browser cannot file "$2,000,000" beside a $900 rent.

    Validated INSIDE the route, not by the envelope: a calculation that fails
    these bounds is dropped with a warning and the lead is captured anyway.
    The `session_id` comment below says why in the analytics' words — a
    pattern on the envelope turns a page bug into a lost person — and a
    calculator is a courtesy, the lead is the point. `extra="forbid"` so an
    unknown key drops the calculation rather than riding along unnoticed.
    """

    model_config = ConfigDict(extra="forbid")

    rent: float = Field(gt=0, le=50_000)
    savings: float = Field(ge=0, le=5_000_000)
    credit: Literal["excellent", "good", "fair"]
    appreciation: float | None = Field(default=None, ge=-0.10, le=0.15)
    rent_growth: float | None = Field(default=None, ge=-0.10, le=0.15)
    rate: float | None = Field(default=None, ge=0.0, le=0.20)
    hoa_monthly: float | None = Field(default=None, ge=0, le=5_000)
    # The horizon selector on the page (5/10/15/20/30). The upper bound is
    # imported rather than typed so it cannot drift away from the scan the
    # comparison actually performs. `extra="forbid"` above is why this field has
    # to exist at all: without it the browser's `years` would not be ignored, it
    # would drop the WHOLE calculation — worse than the bug it fixes.
    years: int | None = Field(default=None, ge=1, le=MAX_YEARS)
    lang: Literal["en", "es"] | None = None


class PublicLeadIn(BaseModel):
    # The public key of the form, as configured in channel_routes. Optional:
    # a single-agency install has nothing to disambiguate, and requiring a key
    # there would mean every customer must run a platform API call before their
    # own contact form works.
    form: str | None = Field(default=None, max_length=254)
    name: str | None = Field(default=None, max_length=MAX_NAME)
    email: str | None = Field(default=None, max_length=254)
    phone: str | None = Field(default=None, max_length=40)
    message: str | None = Field(default=None, max_length=MAX_MESSAGE)
    consent: bool = False
    consent_text: str | None = Field(default=None, max_length=MAX_CONSENT_TEXT)
    utm: dict[str, str] | None = None
    # The landing page's own visit key, when the tracker is running. Its only
    # job is to join this submission to the session that produced it, which is
    # what turns "we got a lead" into "the visit that became this lead came
    # from TikTok, read three sections and tapped call first".
    #
    # A separate field rather than an attribution key on purpose: the whitelist
    # in `capture.py` means "which campaign produced this lead". For a lead
    # born in this submission, the validated key is stored separately as a
    # private acquisition-session marker; later submissions never replace it.
    #
    # Deliberately NOT pinned to the session-key shape here, unlike the beacon's
    # own field. A `pattern` on this model rejects the whole submission with
    # 422, so a bug in the tracker's key generator would stop costing an
    # analytics row and start costing the LEAD — the exact inversion the link
    # below is written to avoid. Bounded only, and checked for shape at the
    # point of use, where a bad value is simply not looked up.
    session_id: str | None = Field(default=None, max_length=64)
    # Positive browser evidence only. False and absence mean "unknown", never
    # "human"; the server combines this with its own user-agent and the exact
    # QA UTM pair before the lead is written.
    webdriver: Literal[True] | None = None
    # The same marker the beacon carries, so a submission we make while testing
    # the form does not arrive in the CRM looking like a customer.
    qa: Literal[True] | None = None
    turnstile_token: str | None = Field(default=None, max_length=4_000)
    # Honeypot. Named for something a browser autofill would plausibly target
    # and hidden in the markup, so a human never sees it and a bot fills it in.
    website: str | None = Field(default=None, max_length=200)
    # Present only when the form sits under /calculator. Travels as its own
    # field, not as an attribution key: the whitelist in `capture.py` means
    # "which campaign produced this lead" and is pinned by tests; a
    # calculation is not that.
    #
    # `Any`, deliberately: `CalculatorIn` is applied in the handler so that a
    # malformed calculation can never make this envelope a 422 — see
    # `CalculatorIn` for why the lead must survive it.
    calculator: Any = None

    # No trimming validator here, deliberately, and it took writing one to find
    # out why: `services/capture.py` already normalises every field that is
    # stored — `clean_text` for name and message (which trims AND collapses
    # runs of whitespace), `normalize_email` and `normalize_phone` for the
    # other two. A validator on this model changed nothing that reached the
    # database; measured on identical POSTs, the stored row was byte-identical
    # with and without it. Code that does nothing is worse than absent: it
    # reads as coverage.
    #
    # Two fields must never acquire one, which is the part worth writing down:
    #
    # - `website` is the honeypot, tested below as `if body.website` — before
    #   the captcha and before tenant resolution. A whitespace-only value is
    #   truthy, so a bot filling the hidden field with spaces is caught today.
    #   Trimming it to None would wave that bot straight through.
    # - `consent_text` reaches `clean_text` like the rest, so it is already
    #   collapsed rather than stored verbatim. Worth knowing before anyone
    #   relies on it reading back exactly as the person saw it.


async def _claim_landing_session(
    db: AsyncSession,
    *,
    org_id: int,
    session_key: str,
    lead_id: int,
    request: Request,
    attribution: dict[str, str],
    traffic_class: str,
    traffic_class_reason: str | None,
) -> None:
    now = datetime.now(UTC)
    referrer_host = referrer_host_of(attribution.get("referrer"))
    user_agent = request.headers.get("user-agent")
    country, region, city = geo_of(request.headers)
    statement = pg_insert(LandingSession).values(
        org_id=org_id,
        session_key=session_key,
        first_seen_at=now,
        last_seen_at=now,
        utm_source=attribution.get("utm_source"),
        utm_medium=attribution.get("utm_medium"),
        utm_campaign=attribution.get("utm_campaign"),
        utm_content=attribution.get("utm_content"),
        utm_term=attribution.get("utm_term"),
        referrer_host=referrer_host,
        source=source_of(attribution.get("utm_source"), referrer_host),
        traffic_class=traffic_class,
        traffic_class_reason=traffic_class_reason,
        traffic_classified_at=now,
        device=device_of(user_agent),
        browser=browser_of(user_agent),
        os=os_of(user_agent),
        in_app=in_app_of(user_agent),
        country=country,
        region=region,
        city=city,
        lead_id=lead_id,
        form_submitted_at=now,
    )
    await db.execute(
        statement.on_conflict_do_update(
            index_elements=["org_id", "session_key"],
            set_={
                "lead_id": lead_id,
                "form_submitted_at": now,
                "updated_at": func.now(),
            },
            where=LandingSession.lead_id.is_(None),
        )
    )


@router.post("/leads", status_code=202)
async def capture(
    body: PublicLeadIn, request: Request, db: AsyncSession = Depends(get_db)
) -> dict[str, bool]:
    ip, ip_is_from_a_proxy_header = _client_ip_parts(request)

    # ── Order matters, and each step is placed for a reason ──────────────
    # 1. Per-IP budget first, charged even for the honeypot. It used to sit
    #    AFTER the honeypot branch, so `{"website": "bot"}` was an unmetered
    #    endpoint: two hundred consecutive posts all answered 202 and left
    #    every counter untouched.
    if _ip_limited(ip):
        log.warning("Rate limit refused a capture from %s", ip)
        raise HTTPException(status_code=429, detail="too_many_requests")

    if body.website:
        # Answer exactly like a good submission. Telling a bot it was detected
        # is free tuning feedback for whoever wrote it.
        log.info("Honeypot tripped from %s", ip)
        return {"ok": True}

    # 2. Shape of the submission, BEFORE the tenant is resolved. A probe with
    #    no email and no phone used to return 422 for a live form key and 404
    #    for a dead one, which made this a quiet enumeration oracle: unlike a
    #    202 probe it writes no lead, so a scan left no trace anywhere the
    #    operator looks. Same answer now regardless of the key.
    # The calculation, bounded here and dropped — not the lead — when it
    # fails. Nothing of the payload is logged; the shape of the failure is.
    calculator: dict | None = None
    if body.calculator is not None:
        try:
            calculator = CalculatorIn.model_validate(body.calculator).model_dump()
        except ValidationError as exc:
            log.warning(
                "Calculator payload refused (%d problem(s)); lead still captured",
                len(exc.errors()),
            )

    gpc = request.headers.get("sec-gpc") == "1"
    submitted_attribution = {} if gpc else (body.utm or {})
    cleaned_attribution = clean_attribution(submitted_attribution)
    traffic_class, traffic_class_reason = (
        ("unknown", None)
        if gpc
        else classify_traffic(
            request.headers.get("user-agent"),
            body.webdriver is True,
            cleaned_attribution,
            body.qa is True,
        )
    )
    analytics_session_id = (
        body.session_id
        if (
            _SESSION_KEY.fullmatch(body.session_id or "")
            and get_settings().LANDING_EVENTS_ENABLED
            and not gpc
        )
        else None
    )
    submission = FormSubmission(
        name=body.name,
        email=body.email,
        phone=body.phone,
        message=body.message,
        consent=body.consent,
        consent_text=body.consent_text,
        attribution=submitted_attribution,
        traffic_class=traffic_class,
        traffic_class_reason=traffic_class_reason,
        landing_session_key=analytics_session_id,
        ip=ip,
        user_agent=request.headers.get("user-agent"),
        calculator=calculator,
    )
    try:
        validate_submission(submission)
    except CaptureRejected as exc:
        raise HTTPException(status_code=422, detail=exc.code) from exc

    # A lead we cannot reach is not a lead. Every field on this form is optional,
    # which was correct while there were two automatic channels; SMS is not one
    # of them today (Twilio accepts and the carrier drops it — error 30034,
    # measured), so a phone-only submission produces a row nobody can answer.
    # Refusing it in front of the person, while they are still on the page and
    # can add an address, is better than accepting it and going quiet.
    #
    # After the captcha check would be wrong: this costs nothing to evaluate and
    # tells an honest visitor what to fix, whereas a bot never gets this far.
    if get_settings().CAPTURE_REQUIRE_EMAIL and not (submission.email or "").strip():
        raise HTTPException(status_code=422, detail="email_required")

    # 3. Captcha before the global budget is touched. A request the captcha
    #    will refuse must not be able to spend a slot: that turned the ceiling
    #    into a kill switch anyone could hold down without solving anything.
    if not await _turnstile_ok(
        body.turnstile_token, ip if ip_is_from_a_proxy_header else None
    ):
        raise HTTPException(status_code=400, detail="captcha_failed")

    # 4. The platform-wide budget, charged BEFORE the tenant lookup rather than
    #    after it. Resolving a form key is a database round trip, and with the
    #    charge at the end a caller rotating the IP header could drive an
    #    unbounded number of them: the per-IP budget resets with every forged
    #    address, so nothing counted the work. Charging here means the ceiling
    #    bounds real work, not just successful writes.
    if _global_limited():
        log.error(
            "Global capture ceiling reached — lead capture is refused for "
            "every agency until the window clears. If this is not a flood, "
            "raise GLOBAL_LIMIT; if it is, configure TURNSTILE_SECRET."
        )
        raise HTTPException(status_code=429, detail="too_many_requests")

    try:
        org_id = await webhook_org_or_refuse(
            CHANNEL_WEB,
            body.form,
            # A key that was supplied must match a route. Without this, an
            # agency offboarded the ordinary way — suspend, delete routes —
            # leaves a live landing page whose submissions get filed into
            # whichever agency remains.
            fallback_when_unmapped=not body.form,
        )
    except WebhookOrgUnresolved as exc:
        # 404, not 503. The form key is public — it ships in the landing page —
        # but the set of valid keys is not, and a distinguishable error turns
        # this endpoint into an oracle for enumerating an operator's tenants.
        log.error("refusing web capture — %s", exc)
        raise HTTPException(status_code=404, detail="unknown_form") from exc

    set_org_id(org_id)

    try:
        captured = await capture_lead(submission, db)
    except CaptureRejected as exc:
        await db.rollback()
        raise HTTPException(status_code=422, detail=exc.code) from exc
    except Exception:
        await db.rollback()
        log.exception("Web capture failed")
        raise HTTPException(status_code=500, detail="capture_failed") from None

    await db.commit()

    # Join the visit to the lead it produced. Wrapped after the lead commit
    # because this is analytics: the lead is already durable, and a failure
    # here must cost a row in a report, never a 500 that sends the
    # visitor round the submit button a second time. This is an upsert because
    # the POST can arrive before the first beacon; the unique session key makes
    # either arrival order converge on one row.
    if (
        analytics_session_id
        and captured.get("lead_id")
    ):
        try:
            await _claim_landing_session(
                db,
                org_id=org_id,
                session_key=analytics_session_id,
                lead_id=int(captured["lead_id"]),
                request=request,
                attribution=cleaned_attribution,
                traffic_class=traffic_class,
                traffic_class_reason=traffic_class_reason,
            )
            await db.commit()
        except Exception as exc:  # noqa: BLE001
            log.warning("Could not link landing session to lead: %s", exc)
            try:
                await db.rollback()
            except Exception:  # noqa: BLE001
                # The rollback is a courtesy — the lead is already durable and
                # the session is about to be discarded either way. Letting this
                # escape would turn an analytics failure into a 500 on a
                # submission that already succeeded, which is the one outcome
                # this whole block exists to prevent.
                log.warning("Rollback after the link failure also failed")

    # After the commit, on purpose: the lead must be durable before anyone is
    # told about it, and a notification failure must cost the notification,
    # never the capture. Duplicates are already filtered — a double-submit
    # returns status "duplicate" above and must not email the agency twice.
    if captured.get("status") == "ok":
        await send_new_lead_notice(captured["lead_id"], captured.get("message_id"))
        # And the visitor gets their own numbers back, when they left any. Inside
        # the same `"ok"` branch on purpose: a duplicate submission must not
        # email them twice, and the status above is already the only place that
        # knows. Sends nothing at all until `POSTAL_ADDRESS` is configured — it
        # says so in the log rather than failing.
        await send_calculator_breakdown(captured["lead_id"])

    # Deliberately says nothing about whether the lead was new, merged or
    # duplicate: that is a membership oracle for anyone who wants to test
    # whether an address is in an agency's book.
    return {"ok": True}


