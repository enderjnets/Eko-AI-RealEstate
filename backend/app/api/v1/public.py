class LandingEventIn(BaseModel, extra="forbid"):
    t: str = Field(max_length=40)
    meta: dict[str, Any] | None = None

    @field_validator("t")
    @classmethod
    def _known(cls, v: str) -> str:
        if v not in LANDING_EVENT_TYPES:
            raise ValueError("unknown event type")
        return v

    @field_validator("meta")
    @classmethod
    def _small(cls, v: dict[str, Any] | None) -> dict[str, Any] | None:
        """Bounded in both directions: at most five keys, and values that are
        short strings or plain numbers. The metadata is a label — which section,
        which percentage, which button — and anything larger arriving here is
        somebody using a public endpoint as free storage."""
        if v is None:
            return None
        if len(v) > 5:
            raise ValueError("too many metadata keys")
        out: dict[str, Any] = {}
        for key, value in v.items():
            if not isinstance(key, str) or len(key) > 40:
                raise ValueError("bad metadata key")
            if isinstance(value, bool) or value is None:
                continue
            if isinstance(value, int):
                out[key] = value
            elif isinstance(value, str):
                trimmed = value.strip()[:120]
                if trimmed:
                    out[key] = trimmed
            else:
                raise ValueError("bad metadata value")
        return out


class LandingBatchIn(BaseModel, extra="forbid"):
    form: str | None = Field(default=None, max_length=254)
    # Random, client-side, and it dies with the tab. Pinned to a shape so a row
    # key can never be an arbitrary string somebody chose.
    session: str = Field(pattern=r"^[0-9a-f]{32}$")
    path: str | None = Field(default=None, max_length=200)
    lang: Literal["en", "es"] | None = None
    screen_w: int | None = Field(default=None, ge=0, le=10_000)
    webdriver: Literal[True] | None = None
    # This browser was marked as one of ours, once, and remembers it. The model
    # forbids extra keys, so the beacon would 422 without this line.
    qa: Literal[True] | None = None
    utm: dict[str, str] | None = None
    referrer: str | None = Field(default=None, max_length=500)
    events: list[LandingEventIn] = Field(min_length=1, max_length=EVENTS_MAX_PER_BATCH)


@router.post("/landing")
async def landing_events(request: Request, db: AsyncSession = Depends(get_db)) -> Response:
    """What a visitor did on the marketing page, before there was a lead.

    Unauthenticated and uncaptcha'd, because it is sent by a page anyone can
    open and by `navigator.sendBeacon`, which cannot solve a challenge and
    cannot wait for one. Three things stand in for the captcha, and the third
    is the one that actually bounds the table: its own rate budget, a 16 KB
    body of at most 25 events with a closed set of names, and a **per-agency
    daily cap on new sessions**. Without that cap the rate limit bounds the
    speed of writing permanent rows and nothing bounds their number.

    Always 204, even when it declines to do anything. The sender has nothing
    useful to do with the distinction, and a public endpoint that answers
    differently for a valid and an invalid form key is an oracle for
    enumerating an operator's tenants. Honest caveat, since a comment that
    overclaims is worse than none: the STATUS is identical, but a resolvable
    key does more work than an unresolvable one, so the two are distinguishable
    by timing to anyone willing to average enough samples.

    The body is read and parsed by hand rather than declared as a Pydantic
    parameter because `sendBeacon` sends `text/plain` — Chromium refuses a JSON
    Blob from a beacon in some contexts — and FastAPI would answer a valid
    batch with 422 purely over the content type.
    """
    if request.headers.get("sec-gpc") == "1":
        return Response(status_code=204)

    ip = client_ip(request)
    if _ev_ip_limited(ip):
        return Response(status_code=429)

    # Charged BEFORE the body is read and parsed. The sibling endpoint carries
    # a comment about the opposite order being a past outage, and the reasoning
    # inverts here: `capture` charges last so a request the captcha will refuse
    # cannot spend the platform's budget. There is no captcha on this path, so
    # a caller rotating the client-IP header would otherwise buffer 16 KB and
    # run a JSON parse per request without ever touching the ceiling.
    if _ev_global_limited():
        _warn_once(_global_warned, "landing", "Landing beacon ceiling reached")
        return Response(status_code=429)

    raw = await request.body()
    if len(raw) > EVENTS_MAX_BODY:
        return Response(status_code=413)
    try:
        payload = json.loads(raw) if raw else None
        body = LandingBatchIn.model_validate(payload)
    except Exception as exc:  # noqa: BLE001
        # 400 for both a malformed body and one that fails validation — the
        # sender is our own script and a distinguishing error helps nobody but
        # somebody probing the schema. But it is LOGGED, once per window: the
        # tracker is the only caller, so a schema drift on its side would make
        # every batch 400 and leave the table at zero with nothing anywhere
        # saying why, and `sendBeacon` has no error handler to notice.
        _warn_once(_reject_warned, "landing", f"Landing beacon rejected: {exc}")
        return Response(status_code=400)

    if not get_settings().LANDING_EVENTS_ENABLED:
        return Response(status_code=204)

    try:
        org_id = await webhook_org_or_refuse(
            CHANNEL_WEB, body.form, fallback_when_unmapped=not body.form
        )
    except WebhookOrgUnresolved as exc:
        log.info("Dropping landing beacon — %s", exc)
        return Response(status_code=204)

    # Bound BEFORE the first query on `db`: the org id is injected into the
    # transaction when it begins, so a query issued before this point runs with
    # an empty `app.current_org_id` and, under default-deny RLS, sees nothing.
    set_org_id(org_id)

    now = datetime.now(UTC)
    batch = [(e.t, e.meta or {}) for e in body.events]

    try:
        session_id = await _landing_session_id(db, org_id, body, request, now)
        if session_id is None:
            return Response(status_code=204)

        await db.execute(
            update(LandingSession)
            .where(LandingSession.id == session_id)
            .values(
                **merge_values(fold_events(batch), now),
                # A successful form POST can win the race and create the
                # session before this first beacon. Preserve that POST's
                # first-touch attribution while filling the page context that
                # only the beacon carries.
                landing_path=func.coalesce(
                    LandingSession.landing_path, _path_only(body.path)
                ),
                lang=func.coalesce(LandingSession.lang, body.lang),
                screen_w=func.coalesce(LandingSession.screen_w, body.screen_w),
            )
        )
        db.add_all(new_events(org_id, session_id, batch, now))
        await db.commit()
    except Exception:
        await db.rollback()
        log.exception("Landing beacon failed")
        # Still 204: the page must not learn anything from a failure here, and
        # a beacon has nobody to report to.
        return Response(status_code=204)

    return Response(status_code=204)


async def _landing_session_id(
    db: AsyncSession,
    org_id: int,
    body: LandingBatchIn,
    request: Request,
    now: datetime,
) -> int | None:
    """The id of this visit's session row, creating it if this is its first
    beacon. None when the agency has already opened its quota of sessions
    today, which is the only thing bounding how many permanent rows an
    anonymous caller can create.

    The cap is on CREATION, not on beacons: a visit already recorded keeps
    merging, so a real visitor is never truncated mid-page — only a caller
    inventing session keys is stopped.
    """
    found = (
        await db.execute(
            select(LandingSession.id).where(
                LandingSession.org_id == org_id,
                LandingSession.session_key == body.session,
            )
        )
    ).scalar_one_or_none()
    if found is not None:
        return found

    if await _sessions_today(db, org_id, now) >= get_settings().LANDING_SESSIONS_PER_DAY:
        _warn_once(
            _cap_warned,
            org_id,
            f"Landing session cap reached for organization {org_id}; new visits "
            "are not being recorded until tomorrow",
        )
        return None

    attribution = clean_attribution(body.utm)
    host = referrer_host_of(body.referrer)
    ua = request.headers.get("user-agent")
    traffic_class, traffic_class_reason = classify_traffic(
        ua, body.webdriver is True, attribution, body.qa is True
    )
    country, region, city = geo_of(request.headers)

    # Core INSERT, not the ORM: `before_flush` is what stamps `org_id` on this
    # project's tables, and it never sees a Core statement. Hence the explicit
    # value — without it the policy's WITH CHECK refuses the row.
    inserted = (
        await db.execute(
            pg_insert(LandingSession)
            .values(
                org_id=org_id,
                session_key=body.session,
                first_seen_at=now,
                last_seen_at=now,
                landing_path=_path_only(body.path),
                lang=body.lang,
                utm_source=attribution.get("utm_source"),
                utm_medium=attribution.get("utm_medium"),
                utm_campaign=attribution.get("utm_campaign"),
                utm_content=attribution.get("utm_content"),
                utm_term=attribution.get("utm_term"),
                referrer_host=host,
                source=source_of(attribution.get("utm_source"), host),
                traffic_class=traffic_class,
                traffic_class_reason=traffic_class_reason,
                traffic_classified_at=now,
                device=device_of(ua),
                browser=browser_of(ua),
                os=os_of(ua),
                in_app=in_app_of(ua),
                country=country,
                region=region,
                city=city,
                screen_w=body.screen_w,
            )
            # First touch wins, exactly as it does for a lead's attribution: a
            # visitor who reloads with a different query string has not changed
            # where they came from. Also the race: two first beacons for one
            # visit, and the loser reads the winner's row below.
            .on_conflict_do_nothing(index_elements=["org_id", "session_key"])
            .returning(LandingSession.id)
        )
    ).scalar_one_or_none()
    if inserted is not None:
        return inserted

    return (
        await db.execute(
            select(LandingSession.id).where(
                LandingSession.org_id == org_id,
                LandingSession.session_key == body.session,
            )
        )
    ).scalar_one_or_none()


async def _sessions_today(db: AsyncSession, org_id: int, now: datetime) -> int:
    """How many visits this agency has opened since local midnight.

    Local, not UTC, because every number this feature produces is read against
    the agency's own day and a cap that resets at 5pm Denver time would be
    surprising in exactly the way an operator does not need. Counted through a
    LIMIT so the scan stops at the cap instead of walking a busy day's rows.
    """
    cap = get_settings().LANDING_SESSIONS_PER_DAY
    zone = await _agency_zone(db)
    midnight = now.astimezone(zone).replace(hour=0, minute=0, second=0, microsecond=0)
    window = (
        select(LandingSession.id)
        .where(
            LandingSession.org_id == org_id,
            LandingSession.first_seen_at >= midnight.astimezone(UTC),
        )
        .limit(cap)
        .subquery()
    )
    return (
        await db.execute(select(func.count()).select_from(window))
    ).scalar_one()


async def _agency_zone(db: AsyncSession):
    """The acting agency's timezone, or UTC if it has not set a usable one."""
    from app.models import AgentSettings
    from app.services.timezones import resolve_zone

    name = (
        await db.execute(select(AgentSettings.timezone).limit(1))
    ).scalar_one_or_none()
    return resolve_zone(name or "") or UTC


@router.api_route("/content/{piece_id}/media", methods=["GET", "HEAD"])
async def public_media(request: Request, piece_id: int):
    """The video, for the platform that is about to post it.

    Unauthenticated because Buffer has no session and cannot get one: it takes
    a URL and downloads from it when the post goes out. The gate is the piece's
    status, not the address — see `services/media_public.py` for why the signed
    link this repo would otherwise reach for cannot work here.

    Range requests are answered here rather than left to `FileResponse`, which
    in this Starlette version ignores them and returns the whole file with a
    200. Media fetchers ask for ranges, and a client that insists would see a
    broken video hours after the post was created.

    **HEAD as well as GET, and that is not tidiness.** Starlette's own `Route`
    adds HEAD to anything that answers GET; FastAPI's `APIRoute` does not, so
    `@router.get` alone returns 405 to a HEAD. Buffer asks HEAD first to see
    whether the media is really there, and on the 405 gave up with "Video could
    not be read from its URL" — a message that points at the file, the URL and
    the tunnel, none of which were the problem. Measured on the first real
    publish attempt: `HEAD /api/v1/public/content/3/media 405`.
    """
    path = await resolve_public_media(piece_id)
    if path is None:
        # The same answer for "no such piece", "not approved" and "file gone".
        raise HTTPException(status_code=404, detail="Not found")

    size = path.stat().st_size
    # Nothing in between may keep a copy: an edit revokes the piece's approval,
    # and a cached body would outlive that decision.
    headers = {"Cache-Control": "no-store", "Accept-Ranges": "bytes"}

    if request.method == "HEAD":
        # The headers a fetcher is asking for, and no body — the point of the
        # request is to learn the size and type before spending the download.
        return Response(
            status_code=200,
            media_type="video/mp4",
            headers={**headers, "Content-Length": str(size)},
        )

    try:
        span = parse_range(request.headers.get("range"), size)
    except ValueError:
        # Saying so, rather than sending bytes nobody asked for and letting the
        # client believe it got what it wanted.
        return Response(
            status_code=416, headers={**headers, "Content-Range": f"bytes */{size}"}
        )

    if span is None:
        return FileResponse(path, media_type="video/mp4", headers=headers)

    first, last = span
    return StreamingResponse(
        read_range(path, first, last),
        status_code=206,
        media_type="video/mp4",
        headers={
            **headers,
            "Content-Range": f"bytes {first}-{last}/{size}",
            "Content-Length": str(last - first + 1),
        },
    )


# ── The partner brief ────────────────────────────────────────────────────
# A page we hand to the two agents this install is built for, reached by a link
# and answered by tapping. No session, because the whole point is that somebody
# who does not work inside this product can answer without one; the token in
# the path is the credential.
#
# That makes this the fourth caller with login's problem — it must find an
# organization *before* an organization is known — and it is solved login's
# way, not by widening anything: the bypass engine maps token → org and does
# nothing else, and every read and write after that runs on the ordinary
# RLS-enforcing session inside that org. A bug in the queries below can
# therefore leak one tenant's brief at worst, never the table.

# `secrets.token_urlsafe` output: base64url, no padding. Checked before the
# database is touched so a flood of rubbish costs a regex and not a round trip
# — and answered identically to a well-formed token that does not exist, so
# this cannot be used to learn what a real one looks like.
_BRIEF_TOKEN = re.compile(r"[A-Za-z0-9_-]{16,64}")


class BriefAnswersIn(BaseModel):
    """What the page saves. Deliberately unshaped beyond this.

    `answers` is whatever that brief's page decided to collect, because the
    briefs differ from one week to the next and a schema here would have to be
    migrated for every question we think of. It is bounded by size rather than
    by shape — see BRIEF_MAX_ANSWERS — which is the property that actually
    protects the column.
    """

    model_config = ConfigDict(extra="forbid")

    answers: dict[str, Any] = Field(default_factory=dict)
    #: True when a person pressed the button, false when the page autosaved.
    #: See `_should_notify` for why the difference has to reach the server.
    notify: bool = False


async def _brief_org(token: str) -> tuple[int, int] | None:
    """Map a token to `(brief id, org id)`, or None.

    The only query in this module that runs outside a tenant, and it reads two
    integers. Keeping it that small is what keeps the bypass justified.
    """
    async with get_bypass_session_factory()() as meta:
        row = (
            await meta.execute(
                select(PartnerBrief.id, PartnerBrief.org_id).where(
                    PartnerBrief.token == token
                )
            )
        ).first()
    return (int(row[0]), int(row[1])) if row else None


async def _brief_or_404(token: str, request: Request) -> tuple[int, int]:
    """Budget, then resolve. Raises the same 404 for every kind of miss."""
    ip = client_ip(request)
    if _brief_ip_limited(ip):
        log.warning("Brief rate limit refused a request from %s", ip)
        raise HTTPException(status_code=429, detail="too_many_requests")
    if _brief_global_limited():
        log.error("Global brief ceiling reached — briefs are refused until it clears")
        raise HTTPException(status_code=429, detail="too_many_requests")

    if not _BRIEF_TOKEN.fullmatch(token or ""):
        raise HTTPException(status_code=404, detail="unknown_brief")
    found = await _brief_org(token)
    if found is None:
        # Same body, same status, same timing class as a token that exists but
        # is not yours to have. There is nothing to learn here.
        raise HTTPException(status_code=404, detail="unknown_brief")
    return found


@router.get("/brief/{token}")
async def brief_read(
    token: str, request: Request, db: AsyncSession = Depends(get_db)
) -> dict[str, Any]:
    """The brief itself, plus whatever has been answered so far."""
    brief_id, org_id = await _brief_or_404(token, request)
    set_org_id(org_id)

    brief = await db.get(PartnerBrief, brief_id)
    if brief is None:
        # The row vanished between the two queries. Not reachable in practice;
        # answered like any other miss rather than as a 500, because from the
        # caller's side it is the same fact.
        raise HTTPException(status_code=404, detail="unknown_brief")

    # Stamped once, never refreshed: the question this answers is "have they
    # seen it", and that stops changing the moment it is yes. Overwriting it on
    # every load would turn a fact we use to decide whether to phone somebody
    # into a last-seen timestamp nobody asked for.
    first_open = brief.opened_at is None
    if first_open:
        brief.opened_at = datetime.now(UTC)
        try:
            await db.commit()
        except Exception:  # noqa: BLE001 — reading the page must not depend on it
            await db.rollback()
            log.warning("Could not stamp opened_at on brief %d", brief_id)
            first_open = False

    # After the stamp, and only when the stamp is the one that landed: the
    # doorbell rings for the first open and never again, which is exactly what
    # `opened_at` already means. Ringing it before the commit would announce an
    # open that a rolled-back transaction says never happened.
    if first_open:
        await notify_opened(brief)

    return {
        "title": brief.title,
        "recipient": brief.recipient,
        "payload": brief.payload or {},
        "answers": brief.answers or {},
        "answered_at": brief.answered_at.isoformat() if brief.answered_at else None,
    }


#: How long a typing session goes quiet for before another autosave is worth
#: an email. Sized so a person filling the whole brief in one sitting produces
#: one notice at the start and one when they press the button, rather than one
#: per keystroke-pause.
BRIEF_NOTIFY_QUIET = timedelta(minutes=30)


def _should_notify(deliberate: bool, previous: datetime | None) -> bool:
    """Whether this save is worth telling the operator about.

    The page autosaves about a second after the last keystroke, which is right
    for not losing answers and catastrophic for the inbox: measured in
    production on 13-sep-2026, ninety seconds of typing produced EIGHT emails.
    Notifying on every save was not a bug in the sending, it was a design
    mistake — the notice was written for an event that turned out to happen
    every second and a half.

    So: a deliberate press always tells us, because that is a person saying
    "I am done". An autosave tells us only if the brief has been quiet, so
    somebody who fills it in and never finds the button is still not silent —
    which is the case the notice exists for.
    """
    if deliberate:
        return True
    if previous is None:
        return True
    return datetime.now(UTC) - previous >= BRIEF_NOTIFY_QUIET


@router.post("/brief/{token}")
async def brief_save(
    token: str,
    body: BriefAnswersIn,
    request: Request,
    db: AsyncSession = Depends(get_db),
) -> dict[str, Any]:
    """Replace the answers on this brief.

    Replace, not merge, and that is the safe direction here: the page sends its
    whole state on every save, so a merge would make un-ticking something
    impossible — the cleared key simply would not be in the payload, and the
    old value would survive as a decision nobody made. Concurrent editors are
    not a scenario worth trading that for; there are two readers and they are
    in the same house.
    """
    brief_id, org_id = await _brief_or_404(token, request)

    # Bounded before it is stored, not after. Measured against the serialized
    # form rather than the number of keys: what has to stay small is the row.
    if len(json.dumps(body.answers)) > BRIEF_MAX_ANSWERS:
        raise HTTPException(status_code=413, detail="answers_too_large")

    set_org_id(org_id)
    brief = await db.get(PartnerBrief, brief_id)
    if brief is None:
        raise HTTPException(status_code=404, detail="unknown_brief")

    notify = _should_notify(body.notify, brief.answered_at)
    # Both gates read `answered_at` as it was BEFORE this save overwrites it,
    # and both have to be decided here for that reason. They are not the same
    # question: the email carries the answers, the doorbell carries how far
    # along they are, and only the button means finished.
    ping = should_ping_progress(brief.answered_at)
    brief.answers = body.answers
    brief.answered_at = datetime.now(UTC)
    try:
        await db.commit()
    except Exception:
        await db.rollback()
        log.exception("Could not save answers on brief %d", brief_id)
        raise HTTPException(status_code=500, detail="save_failed") from None

    # After the commit, for the same reason the lead notice is: the answers
    # must be durable before anybody is told about them, and a mail failure
    # must cost the mail, never the save. The page is told it saved either way.
    if notify:
        await send_brief_answered_notice(brief_id)

    # The doorbell, after the letter and after the same commit. "Finished" is
    # the press and nothing else — an autosave that announced somebody had
    # finished would be the one message worth interrupting a day for, sent
    # about a person who is still typing. Otherwise a coalesced checkpoint,
    # and a press is never also a checkpoint: two notices about one save is
    # the flood this module exists to avoid.
    if body.notify:
        await notify_finished(brief)
    elif ping:
        await notify_progress(brief)

    return {"ok": True, "answered_at": brief.answered_at.isoformat()}


# ── Unsubscribe: the switch a commercial email has to carry ──────────────


async def _unsubscribe_target(token: str) -> tuple[int, int] | None:
    """Map a signed token to `(lead id, org id)`, or None.

    The second query in this module that runs outside a tenant, and like
    `_brief_org` it reads two integers and nothing else. The bypass is the same
    justification login has: a stranger arriving with a token has to be resolved
    to an organization BEFORE anything can be scoped to one. The token is signed,
    so this cannot be walked with guessed ids.
    """
    lead_id = lead_id_from_token(token)
    if lead_id is None:
        return None
    async with get_bypass_session_factory()() as meta:
        row = (
            await meta.execute(select(Lead.id, Lead.org_id).where(Lead.id == lead_id))
        ).first()
    return (int(row[0]), int(row[1])) if row else None


def _unsubscribe_page(title: str, body: str, *, form_action: str | None = None) -> HTMLResponse:
    """One self-contained page. No stylesheet, no script, no tracking pixel:
    somebody who is asking us to stop should not be measured on the way out."""
    button = (
        f'<form method="post" action="{form_action}">'
        '<button type="submit">Unsubscribe</button></form>'
        if form_action
        else ""
    )
    return HTMLResponse(
        "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\">"
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        '<meta name="robots" content="noindex">'
        f"<title>{title}</title></head>"
        '<body style="font-family:Georgia,serif;max-width:34rem;margin:12vh auto;padding:0 1.5rem;line-height:1.6">'
        f"<h1 style=\"font-weight:400\">{title}</h1><p>{body}</p>{button}</body></html>"
    )


@router.get("/unsubscribe/{token}", response_class=HTMLResponse)
async def unsubscribe_confirm(token: str) -> HTMLResponse:
    """Ask, do not act.

    A GET that unsubscribed on sight would be fired by every link-scanning
    security appliance and spam filter that opens a message before its recipient
    does, and the person would be silently removed from a list they never asked
    to leave. That is why RFC 8058 exists: the POST below is what a mail client's
    own Unsubscribe button sends, so the one-click experience is preserved for
    the reader while a prefetch changes nothing.

    The same page for a token that names nobody. A stranger learns whether a
    signature is valid — which they already knew, having been given it — and
    never whether a lead exists.
    """
    return _unsubscribe_page(
        "Unsubscribe",
        "Confirm and we will stop sending you automated email.",
        form_action=f"/api/v1/public/unsubscribe/{token}",
    )


@router.post("/unsubscribe/{token}", response_class=HTMLResponse)
async def unsubscribe(token: str, db: AsyncSession = Depends(get_db)) -> HTMLResponse:
    """Honour it, and say so.

    Sets `opted_out_at`, which `capture.may_send_automated` reads FIRST for every
    channel — so this silences automated SMS and WhatsApp too, not just email.
    That is deliberate and it is the policy already written into that function:
    "stop means stop", broader than either statute requires. A realtor can still
    write to them personally; nothing automated will.

    The first opt-out wins the date, exactly as the STOP path in
    `conversation.py` has it: the day the agency was first on notice is the
    difference between one violation and thirty, and a second click must not
    reset it.

    Always answers 200 with the same page. A token that names a deleted lead, a
    forged signature and an honest unsubscribe are indistinguishable from
    outside; and a mail client performing RFC 8058 one-click needs a 2xx or it
    tells the reader the unsubscribe failed.
    """
    done = _unsubscribe_page(
        "You are unsubscribed",
        "You will not receive automated email from us again. If you are in the "
        "middle of a conversation with your agent, she can still reply to you "
        "herself.",
    )
    found = await _unsubscribe_target(token)
    if found is None:
        return done
    lead_id, org_id = found
    # Scoped from here on: the bypass above resolved WHICH agency, and the write
    # belongs inside it.
    set_org_id(org_id)
    lead = (await db.execute(select(Lead).where(Lead.id == lead_id))).scalar_one_or_none()
    if lead is None:
        return done
    if lead.opted_out_at is None:
        lead.opted_out_at = datetime.now(UTC)
        lead.opted_out_channel = "email"
        lead.opted_out_keyword = OPT_OUT_KEYWORD
        await db.commit()
        log.info("Lead %d unsubscribed from email", lead_id)
    return done
